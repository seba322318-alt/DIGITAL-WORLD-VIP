  about_text text default 'Capacitación paso a paso, recursos descargables y contenido organizado por membresía.',
  transfer_details text default 'Configura aquí tus datos de transferencia desde el panel administrador.',
  updated_at timestamptz default now()
);
insert into public.site_settings(id) values(1) on conflict do nothing;

